CREATE OR REPLACE VIEW v_student_attendance_summary AS
SELECT
  s.student_id,
  s.roll_number,
  s.student_name,
  c.classroom_name,
  COUNT(cs.session_id) AS total_sessions,
  SUM(CASE WHEN a.status = 'PRESENT' THEN 1 ELSE 0 END) AS present_count,
  SUM(CASE WHEN a.status = 'LATE' THEN 1 ELSE 0 END) AS late_count,
  SUM(CASE WHEN a.status = 'ABSENT' OR a.attendance_id IS NULL THEN 1 ELSE 0 END) AS absent_or_missing_count,
  ROUND(
    100 * SUM(CASE WHEN a.status IN ('PRESENT', 'LATE') THEN 1 ELSE 0 END)
    / NULLIF(COUNT(cs.session_id), 0),
    2
  ) AS attendance_percentage
FROM students s
JOIN classrooms c
  ON c.classroom_id = s.classroom_id
LEFT JOIN class_sessions cs
  ON cs.classroom_id = s.classroom_id
 AND cs.session_status <> 'CANCELLED'
LEFT JOIN attendance a
  ON a.session_id = cs.session_id
 AND a.student_id = s.student_id
GROUP BY s.student_id, s.roll_number, s.student_name, c.classroom_name;

CREATE OR REPLACE VIEW v_daily_class_summary AS
SELECT
  cs.session_id,
  cs.session_date,
  c.classroom_name,
  cs.topic,
  cs.session_status,
  COUNT(a.attendance_id) AS recorded_students,
  SUM(CASE WHEN a.status = 'PRESENT' THEN 1 ELSE 0 END) AS present_count,
  SUM(CASE WHEN a.status = 'LATE' THEN 1 ELSE 0 END) AS late_count,
  SUM(CASE WHEN a.status = 'ABSENT' THEN 1 ELSE 0 END) AS absent_count,
  ROUND(
    100 * SUM(CASE WHEN a.status IN ('PRESENT', 'LATE') THEN 1 ELSE 0 END)
    / NULLIF(COUNT(a.attendance_id), 0),
    2
  ) AS attendance_percentage
FROM class_sessions cs
JOIN classrooms c
  ON c.classroom_id = cs.classroom_id
LEFT JOIN attendance a
  ON a.session_id = cs.session_id
GROUP BY cs.session_id, cs.session_date, c.classroom_name, cs.topic, cs.session_status;

