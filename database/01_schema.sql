CREATE TABLE classrooms (
  classroom_id    VARCHAR2(20)   CONSTRAINT pk_classrooms PRIMARY KEY,
  classroom_name  VARCHAR2(120)  NOT NULL,
  latitude        NUMBER(10,7)   NOT NULL,
  longitude       NUMBER(10,7)   NOT NULL,
  radius_meters   NUMBER(8,2)    DEFAULT 50 NOT NULL,
  teacher_name    VARCHAR2(120),
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_classroom_lat CHECK (latitude BETWEEN -90 AND 90),
  CONSTRAINT ck_classroom_lng CHECK (longitude BETWEEN -180 AND 180),
  CONSTRAINT ck_classroom_radius CHECK (radius_meters > 0)
);

CREATE TABLE students (
  student_id       VARCHAR2(20)   CONSTRAINT pk_students PRIMARY KEY,
  roll_number      VARCHAR2(30)   NOT NULL,
  student_name     VARCHAR2(120)  NOT NULL,
  classroom_id     VARCHAR2(20)   NOT NULL,
  parent_email     VARCHAR2(254),
  parent_phone     VARCHAR2(30),
  face_image_url   CLOB,
  status           VARCHAR2(10)   DEFAULT 'ACTIVE' NOT NULL,
  created_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_students_roll UNIQUE (roll_number),
  CONSTRAINT fk_students_classroom FOREIGN KEY (classroom_id)
    REFERENCES classrooms(classroom_id),
  CONSTRAINT ck_students_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE class_sessions (
  session_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                   CONSTRAINT pk_class_sessions PRIMARY KEY,
  classroom_id     VARCHAR2(20)   NOT NULL,
  session_date     DATE           NOT NULL,
  start_time       TIMESTAMP      NOT NULL,
  end_time         TIMESTAMP,
  topic            VARCHAR2(200),
  session_status   VARCHAR2(12)   DEFAULT 'OPEN' NOT NULL,
  created_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_sessions_classroom FOREIGN KEY (classroom_id)
    REFERENCES classrooms(classroom_id),
  CONSTRAINT uq_session_day UNIQUE (classroom_id, session_date),
  CONSTRAINT ck_session_status CHECK (session_status IN ('OPEN', 'COMPLETED', 'CANCELLED')),
  CONSTRAINT ck_session_time CHECK (end_time IS NULL OR end_time > start_time)
);

CREATE TABLE attendance (
  attendance_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                      CONSTRAINT pk_attendance PRIMARY KEY,
  session_id          NUMBER         NOT NULL,
  student_id          VARCHAR2(20)   NOT NULL,
  recorded_at         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  status              VARCHAR2(10)   NOT NULL,
  confidence          NUMBER(5,2),
  latitude            NUMBER(10,7),
  longitude           NUMBER(10,7),
  verification_method VARCHAR2(20)   DEFAULT 'MANUAL' NOT NULL,
  synced_offline      CHAR(1)        DEFAULT 'N' NOT NULL,
  snapshot_url        VARCHAR2(1000),
  notes               VARCHAR2(1000),
  CONSTRAINT fk_attendance_session FOREIGN KEY (session_id)
    REFERENCES class_sessions(session_id) ON DELETE CASCADE,
  CONSTRAINT fk_attendance_student FOREIGN KEY (student_id)
    REFERENCES students(student_id),
  CONSTRAINT uq_attendance_student_session UNIQUE (session_id, student_id),
  CONSTRAINT ck_attendance_status CHECK (status IN ('PRESENT', 'ABSENT', 'LATE')),
  CONSTRAINT ck_attendance_confidence CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 100),
  CONSTRAINT ck_attendance_lat CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  CONSTRAINT ck_attendance_lng CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
  CONSTRAINT ck_attendance_method CHECK (verification_method IN ('FACE_RECOGNITION', 'MANUAL', 'OFFLINE_SYNC')),
  CONSTRAINT ck_attendance_sync CHECK (synced_offline IN ('Y', 'N'))
);

CREATE TABLE parent_alerts (
  alert_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
